// What Furnace's text export says of a .fur: its information, chips, channels and subsongs.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFurnaceText } from './furnace-text.ts';

const TEXT = `# Furnace Text Export

generated by Furnace 0.6.8.3 (232)

# Song Information

- name: Bridge Zone
- author: Yuzo Koshiro     Arr. RevvoBolt
- album: Sonic the Hedgehog (Master System)
- system: Famicom with Konami VRC6
- tuning: 440

# Sound Chips

- NES (Ricoh 2A03)
  - id: 08
  - volume: 1
- Konami VRC6
  - id: 1B

# Song Comments

Sonic the Hedgehog on the Famicom?
# Instruments

## 00: Pulse/Triangle

# Subsongs

## 0: Bridge Zone

- tick rate: 60

orders:
\`\`\`
00 | 00 00 00 00 00 00 00 00
01 | 01 01 01 01 01 01 01 01
\`\`\`

## 1: Ending

orders:
\`\`\`
00 | 00 00 00 00 00
\`\`\`

## Patterns
`;

test('a text export gives the name, the chips, the first subsong channels and the subsongs', () => {
  assert.deepEqual(readFurnaceText(TEXT), {
    name: 'Bridge Zone',
    author: 'Yuzo Koshiro     Arr. RevvoBolt',
    album: 'Sonic the Hedgehog (Master System)',
    chips: ['NES (Ricoh 2A03)', 'Konami VRC6'],
    channelCount: 8,
    subsongCount: 2,
  });
});

test('a text without the sections gives empty facts', () => {
  assert.deepEqual(readFurnaceText(''), {
    name: '',
    author: '',
    album: '',
    chips: [],
    channelCount: 0,
    subsongCount: 0,
  });
});
